"""Export the portable pip requirements from uv.lock, including the explicit CPU wheel index."""

import subprocess
import tomllib
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    content = subprocess.check_output(
        [
            "uv",
            "export",
            "--frozen",
            "--extra",
            "models",
            "--no-dev",
            "--no-emit-project",
            "--no-hashes",
            "--no-header",
            "--format",
            "requirements-txt",
        ],
        cwd=root,
        text=True,
    )
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    indexes = project["tool"]["uv"]["index"]
    header = "# Generated by python -m scripts.export_requirements from uv.lock\n"
    header += "".join("--extra-index-url " + index["url"] + "\n" for index in indexes)
    (root / "requirements.txt").write_text(header + content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
